#!/usr/bin/env python3
"""Embed binary files (compiled shaders) in a C++ header.

Usage: bin2h.py OUT.h FILE...   ->  alignas(256) static const unsigned char k_<name>[] = {...};
"""
import os, sys

out = sys.argv[1]
with open(out, 'w') as f:
    f.write('// Generated by tools/bin2h.py - do not edit.\n#pragma once\n\n')
    for path in sys.argv[2:]:
        name = os.path.splitext(os.path.basename(path))[0]
        data = open(path, 'rb').read()
        f.write('alignas(256) static const unsigned char k_%s[] = {\n' % name)
        for i in range(0, len(data), 16):
            f.write('    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',\n')
        f.write('};\n\n')
