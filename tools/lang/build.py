#!/usr/bin/env python3
# Brume - v64/v65: the languages, made and CHECKED at every build (scripts/build.sh runs it with --check).
#   1. writes src/LangTable.inc from tools/lang/en.py;
#   2. --check: every French text of the menu (in src/) must have its English in en.py, and a French text used to BUILD a
#      text (snprintf) must go through lang::T(...) - otherwise the build stops and says which text, where.
#      (Texts drawn as they are - Ui::TextCentered, Toast, rows of the settings - are translated when drawn.)
#   python3 tools/lang/build.py [--check]
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '..', 'src')
sys.path.insert(0, HERE)
from en import EN

BS = chr(92)                                             # a backslash (no escaping games in this file)

def c_str(s):
    out = '"'
    for ch in s:
        if ch == '"': out += BS + '"'
        elif ch == BS: out += BS + BS
        elif ord(ch) < 0x80: out += ch
        else: out += ''.join(BS + 'x%02x' % b for b in ch.encode('utf-8')) + '" "'   # (a new literal after: no hex run-on)
    return out + '"'

FMT = re.compile(r'%[-+ #0-9.]*[a-zA-Z%]')
lines = ['// Generated by tools/lang/build.py from tools/lang/en.py - do not edit by hand.']
for fr, en in EN.items():
    if fr == en: continue
    assert FMT.findall(fr) == FMT.findall(en), 'les %% ne correspondent pas : ' + fr
    lines.append('{ %s, %s },' % (c_str(fr), c_str(en)))
table = '\n'.join(lines) + '\n'
path = os.path.join(SRC, 'LangTable.inc')
if not os.path.exists(path) or open(path, encoding='utf-8').read() != table:   # (unchanged: not rewritten, no rebuild)
    open(path, 'w', encoding='utf-8').write(table)

if '--check' not in sys.argv:
    print('LangTable.inc : %d textes' % (len(lines) - 1)); sys.exit(0)

def decoded(body):                                       # C escapes -> the real UTF-8 text
    out = bytearray(); i = 0
    while i < len(body):
        c = body[i]
        if c == BS and i + 1 < len(body):
            n = body[i + 1]
            if n == 'x':
                j = i + 2; h = ''
                while j < len(body) and body[j] in '0123456789abcdefABCDEF' and len(h) < 2: h += body[j]; j += 1
                out.append(int(h, 16)); i = j; continue
            out += {'n': b'\n', 't': b'\t', BS: BS.encode(), '"': b'"'}.get(n, n.encode()); i += 2; continue
        out += c.encode('utf-8'); i += 1
    return out.decode('utf-8', 'replace')

ACCENTS = set('éèàçùêâîôûëïüœÉÈÀÇÊÂÎÔÛ«»')
WORDS = re.compile(r"\b(de|la|le|les|des|du|et|pour|sur|tes|ton|ta|une|aucun|aucune|appuie|choisir|ouvrir|fermer|retour|jeux|jeu|"
                   r"manette|manettes|réglages|lancer|carte|erreur|introuvable|impossible|joueur|profil|pseudo)\b", re.I)
def looks_french(t):
    return any(ch in ACCENTS for ch in t) or bool(WORDS.search(t))

# texts that are French on purpose and never drawn (logs, files written for people who read French, keys)
LOGS = re.compile(r'\b(LogLine|Log|LogSystem|Fail|fprintf|fputs|printf|sscanf|s_log|Probe)\s*\($')
KEEP = {s for s in (
    '# Brume - les emulateurs de chaque console',     # (the start of emulateurs.ini's template: a file, in French)
)}

LIT = re.compile('"((?:[^"' + BS + BS + r'\n]|' + BS + BS + '.)*)"')
errors = []
for fn in sorted(os.listdir(SRC)):
    if not fn.endswith(('.cpp', '.hpp')): continue
    text = open(os.path.join(SRC, fn), encoding='utf-8').read()
    clean = re.sub(r'/\*.*?\*/', lambda m: re.sub(r'[^\n]', ' ', m.group(0)), text, flags=re.S)
    out, i = [], 0                                       # // comments blanked (outside strings)
    while i < len(clean):
        c = clean[i]
        if c == '"':
            j = i + 1
            while j < len(clean) and clean[j] != '"': j += 2 if clean[j] == BS else 1
            out.append(clean[i:j + 1]); i = j + 1; continue
        if c == "'" and i + 2 < len(clean):
            j = clean.find("'", i + 1 + (1 if clean[i + 1] == BS else 0) + 1)
            if j > 0 and j - i <= 6: out.append(clean[i:j + 1]); i = j + 1; continue
        if clean.startswith('//', i):
            j = clean.find('\n', i); j = len(clean) if j < 0 else j
            out.append(' ' * (j - i)); i = j; continue
        out.append(c); i += 1
    clean = ''.join(out)
    pos = 0
    for m in re.finditer('(?:' + LIT.pattern + r'\s*)+', clean):
        if m.start() < pos: continue
        pos = m.end()
        txt = decoded(''.join(LIT.findall(m.group(0))))
        if not looks_french(txt) or '#include' in clean[clean.rfind('\n', 0, m.start()):m.start()]: continue
        stmt_start = max(clean.rfind(';', 0, m.start()), clean.rfind('{', 0, m.start()), clean.rfind('}', 0, m.start())) + 1
        stmt = clean[stmt_start:m.start()]
        if any(LOGS.search(stmt[:k.end()]) for k in re.finditer(r'\(', stmt)): continue     # inside a log / file call
        if txt.startswith(('sdmc:', '/')) or any(txt.startswith(k) for k in KEEP): continue
        if re.fullmatch(r'[a-z0-9_]+', txt): continue                 # an identifier (« manettes », « profil »...)
        line = clean.count('\n', 0, m.start()) + 1
        if 'lang:' in text.split('\n')[line - 1]: continue            # marked in the code: lang:fr / lang:log
        if txt not in EN:
            errors.append('%s:%d  pas de traduction anglaise : %r' % (fn, line, txt)); continue
        if 'snprintf(' in stmt and not stmt.rstrip().endswith('lang::T(') and EN[txt] != txt:
            errors.append('%s:%d  texte construit sans lang::T() : %r' % (fn, line, txt))
if errors:
    print('LANGUES : %d probleme(s) - ajoute la traduction dans tools/lang/en.py ou passe le texte par lang::T() :' % len(errors))
    for e in errors: print('  ' + e)
    sys.exit(1)
print('langues OK : %d textes traduits, tous les textes du menu ont leur anglais' % (len(lines) - 1))
