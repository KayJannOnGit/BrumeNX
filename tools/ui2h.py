#!/usr/bin/env python3
# assets/ui/layout.json (measured in the browser on the mockup's own CSS by tools/bake-assets.html)
# -> build/ui_layout.h : the positions of the wheel's glass panels and of the clock text.
import json, sys
L = json.load(open(sys.argv[2], encoding='utf-8'))
f = lambda v: ', '.join('%.2ff' % x for x in v)
out = ['// generated by tools/ui2h.py from assets/ui/layout.json - do not edit', '#pragma once', 'namespace brume::layout {',
       '    constexpr float kTopBar[5] = { %s };   // x, y, w, h, radius (menu px)' % f(L['topBar']),
       '    constexpr float kTimeRight = %.2ff, kTimeBaseline = %.2ff, kTimeLetterSpacing = %.2ff;' % (L['time']['right'], L['time']['baseline'], L['time']['ls']),
       '    constexpr float kPlate[%d][5] = {' % len(L['consoles'])]
out += ['        { %s },' % f(c['plate']) for c in L['consoles']]
out += ['    };', '}', '']
open(sys.argv[1], 'w', encoding='utf-8').write('\n'.join(out))
