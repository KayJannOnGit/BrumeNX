# uisim - every function the menu calls that the PC does not have (libnx, the loader's qext_*, deko3d...) becomes a
# stub: the ones that return a libnx Result FAIL (the menu takes its "service unavailable" path, as it must handle
# anyway), the others return 0 (no titles, no file, nothing).
#   python3 gen_stubs.py <ld errors> <libnx include dir> <out stubs.c>
import re, sys, os
errs, inc, out = sys.argv[1], sys.argv[2], sys.argv[3]
names = sorted(set(re.findall(r"undefined reference to `([^']+)'", open(errs, encoding='utf-8', errors='replace').read())))
results = set()
for root, _, files in os.walk(inc):
    for fn in files:
        if fn.endswith('.h'):
            for m in re.finditer(r'\bResult\s+(\w+)\s*\(', open(os.path.join(root, fn), encoding='utf-8', errors='replace').read()):
                results.add(m.group(1))
with open(out, 'w') as f:
    f.write('// generated by gen_stubs.py - do not edit\n')
    for i, n in enumerate(names):
        rv = '0x2A2' if n in results else '0'
        f.write('unsigned long long s%d(void) __asm__("%s");\nunsigned long long s%d(void) { return %s; }\n' % (i, n, i, rv))
print('%d stubs (%d Result)' % (len(names), sum(1 for n in names if n in results)))
