# Brume Overlay - pre-renders the overlay's text at build time (PIL / FreeType on the PC), like the menu's tools/fontbake.cpp:
# the console only copies alpha masks (no font code, no FreeType, nothing to fail at run time).
# Font: Outfit (SIL OFL 1.1, brume/assets/fonts/OFL-Outfit.txt), the menu's own, at the menu's weights and sizes.
# Usage: python3 bakefont.py FONTDIR OUT.inc
import sys, os
from PIL import Image, ImageDraw, ImageFont

FONTDIR, OUT = sys.argv[1], sys.argv[2]
MIXED = (" ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
         "àâäçéèêëîïôöùûüÿœæÀÂÄÇÉÈÊËÎÏÔÖÙÛÜŒ0123456789,.;:!?'\"()-+/%·’«»…–"
         "#&*=<>[]_@$~^|{}\\`°←↑→↓")   # v98: all of ASCII and ° (the monitor, the game's notes: codes, tips)
# (name, file, weight, px, chars) - px at 1280x720, the size the overlay draws at (1:1 on the handheld screen)
STYLES = [
    ("Title",  "Outfit-wght.ttf", 300, 31, MIXED),   # the yellow titles (the menu's SetSel / PageTitle family)
    ("Item",   "Outfit-wght.ttf", 300, 25, MIXED),   # a choice / a setting's name
    ("Value",  "Outfit-wght.ttf", 300, 21, MIXED),   # its value (the menu's SetOpt)
    ("Small",  "Outfit-wght.ttf", 300, 17, MIXED),   # the date, the clocks, the volume's word
    ("Hint",   "Outfit-wght.ttf", 300, 19, MIXED),   # the hints' words, the notifications (the menu's HintBig)
    ("Button", "Outfit-wght.ttf", 500, 20, "AB"),    # the hints' letters (the menu's Button)
]

glyphs, faces, bitmaps = [], [], []
for name, file, weight, px, chars in STYLES:
    f = ImageFont.truetype(os.path.join(FONTDIR, file), size=px)
    try:
        f.set_variation_by_axes([weight])
    except Exception as e:
        print("variation", name, e)
    asc, desc = f.getmetrics()
    first = len(glyphs)
    seen = set()
    for ch in chars:
        if ch in seen:
            continue
        seen.add(ch)
        cp = ord(ch)
        if cp > 0xFFFF:
            continue
        adv = f.getlength(ch)
        S = px * 3
        im = Image.new('L', (S * 2, S * 2), 0)
        ox, oy = S // 2, S
        ImageDraw.Draw(im).text((ox, oy), ch, font=f, fill=255, anchor='ls')
        bb = im.getbbox()
        if ch != ' ' and not bb:
            continue                                  # (not in the font)
        if bb:
            crop = im.crop(bb)
            bx, by = bb[0] - ox, oy - bb[1]
        else:
            crop, bx, by = None, 0, 0
        glyphs.append([cp, 0, 0, crop.width if crop else 0, crop.height if crop else 0, bx, by, int(round(adv * 64))])
        bitmaps.append(crop)
    faces.append((px, asc, desc, first, len(glyphs) - first))

# shelf packing, 512 wide
W = 512
x = y = rowh = 0
for g, b in zip(glyphs, bitmaps):
    if not b:
        continue
    if x + b.width + 1 > W:
        x, y, rowh = 0, y + rowh + 1, 0
    g[1], g[2] = x, y
    x += b.width + 1
    rowh = max(rowh, b.height)
H = y + rowh + 1
atlas = Image.new('L', (W, H), 0)
for g, b in zip(glyphs, bitmaps):
    if b:
        atlas.paste(b, (g[1], g[2]))
data = atlas.tobytes()

NL = "\n"
with open(OUT, 'w') as o:
    o.write("// generated by overlay/tools/bakefont.py from brume/assets/fonts/Outfit-wght.ttf (SIL OFL 1.1) - do not edit" + NL)
    o.write("struct BGlyph { unsigned short cp, x, y; unsigned char w, h; signed char bx, by; unsigned short adv; };   // adv: 1/64 px" + NL)
    o.write("struct BFace { short px, asc, desc; unsigned short first, count; };" + NL)
    o.write("enum { kBAtlasW = %d, kBAtlasH = %d, kBFaces = %d };" % (W, H, len(faces)) + NL)
    o.write("static const BFace kBFace[%d] = {" % len(faces) + NL)
    for fa in faces:
        o.write("    { %d, %d, %d, %d, %d }," % fa + NL)
    o.write("};" + NL)
    o.write("static const BGlyph kBGlyph[%d] = {" % len(glyphs) + NL)
    for g in glyphs:
        o.write("    { %d, %d, %d, %d, %d, %d, %d, %d }," % tuple(g) + NL)
    o.write("};" + NL)
    o.write("static const unsigned char kBAtlas[%d] = {" % len(data) + NL)
    for i in range(0, len(data), 32):
        o.write(",".join(str(v) for v in data[i:i + 32]) + "," + NL)
    o.write("};" + NL)
print("polices : %d styles, %d glyphes, atlas %dx%d (%d Ko)" % (len(faces), len(glyphs), W, H, len(data) // 1024))
